"""AP 5: dictionary lookup, output and the outer interpreter run on Prim."""
from functools import partial
from prim.isa import PrimOpcodes as Op
from forth.kernel.primitives import Code, emit_word


def emit_console(image):
    c = Code(image)
    word = partial(emit_word, c)

    def set_cell(name, value):
        c.push(value)
        c.store(name)

    def advance(name, amount=1):
        c.load(name)
        c.push(abs(amount))
        c.ops(Op.ADD if amount > 0 else Op.SUB)
        c.store(name)

    def output(text):
        for byte in text:
            c.push(byte)
            c.push('uart_data')
            c.ops(Op.BYTE_STORE)

    def field(name, offset, byte=False):
        c.load(name)
        if offset:
            c.push(offset)
            c.ops(Op.ADD)
        c.ops(Op.BYTE_FETCH if byte else Op.FETCH)

    # ASCII-only case folding, deliberately not bit-masking punctuation.
    c.mark('fold_ascii')  # ( c -- c' ), raw.
    lower, done = c.label('fold_lower'), c.label('fold_done')
    c.ops(Op.DUP)
    c.push(ord('a'))
    c.ops(Op.LTU)
    c.jz(lower)
    c.ops(Op.NOP | 128)
    c.mark(lower)
    c.ops(Op.DUP)
    c.push(ord('z') + 1)
    c.ops(Op.LTU)
    c.jz(done)
    c.push(32)
    c.ops(Op.SUB)
    c.mark(done)
    c.ops(Op.NOP | 128)

    c.mark('find_word')  # ( -- ); current token -> found_header/xt/flags or 0.
    for name in ('found_header', 'found_xt', 'found_flags'):
        set_cell(name, 0)
    finish = c.label('find_return')
    c.load('token_length')
    c.jz(finish)
    c.load('token_length')
    c.push(32)
    c.ops(Op.LTU)
    c.jz(finish)
    c.load('latest')
    c.store('find_header')
    loop, next_header, visible, scan, match, equal_char = (
        c.label('find_' + x) for x in ('loop', 'next', 'visible', 'scan', 'match', 'equal'))
    c.mark(loop)
    c.load('find_header')
    c.jz(finish)
    field('find_header', 2, byte=True)
    c.push(4)
    c.ops(Op.AND)
    c.jz(visible)
    c.jump(next_header)
    c.mark(visible)
    field('find_header', 3, byte=True)
    c.load('token_length')
    c.ops(Op.SUB)
    length_equal = c.label('find_length_equal')
    c.jz(length_equal)
    c.jump(next_header)
    c.mark(length_equal)
    set_cell('find_index', 0)
    c.mark(scan)
    c.load('find_index')
    c.load('token_length')
    c.ops(Op.LTU)
    c.jz(match)
    c.load('token_addr')
    c.load('find_index')
    c.ops(Op.ADD, Op.BYTE_FETCH)
    c.call('fold_ascii')
    c.load('find_header')
    c.push(8)
    c.ops(Op.ADD)
    c.load('find_index')
    c.ops(Op.ADD, Op.BYTE_FETCH)
    c.call('fold_ascii')
    c.ops(Op.SUB)
    c.jz(equal_char)
    c.jump(next_header)
    c.mark(equal_char)
    advance('find_index')
    c.jump(scan)
    c.mark(next_header)
    field('find_header', 0)
    c.store('find_header')
    c.jump(loop)
    c.mark(match)
    c.load('find_header')
    c.store('found_header')
    field('find_header', 4)
    c.store('found_xt')
    field('find_header', 2, byte=True)
    c.store('found_flags')
    c.mark(finish)
    c.ops(Op.NOP | 128)

    # Raw byte spans: print_addr/print_left, no change to the user stack.
    c.mark('print_token')
    c.load('token_addr')
    c.store('print_addr')
    c.load('token_length')
    c.store('print_left')
    c.jump('print_span')
    c.mark('print_span')
    loop, done = c.label('span_loop'), c.label('span_done')
    c.mark(loop)
    c.load('print_left')
    c.jz(done)
    c.load('print_addr')
    c.ops(Op.BYTE_FETCH)
    c.call('raw_emit')
    advance('print_addr')
    advance('print_left', -1)
    c.jump(loop)
    c.mark(done)
    c.ops(Op.NOP | 128)

    c.mark('validate_base')  # Raw, no data-stack effect.
    lower = c.label('format_base_lower')
    c.load('base')
    c.push(2)
    c.ops(Op.LTU)
    c.jz(lower)
    c.jump('error_base')
    c.mark(lower)
    c.load('base')
    c.push(37)
    c.ops(Op.LTU)
    c.jz('error_base')
    c.ops(Op.NOP | 128)

    c.mark('print_unsigned')  # ( u -- ), raw, no trailing space.
    c.store('arith_a')
    c.call('validate_base')
    set_cell('format_count', 0)
    digits, alpha, save, emit, done = (
        c.label('format_' + x) for x in ('digits', 'alpha', 'save', 'emit', 'done'))
    c.mark(digits)
    c.load('base')
    c.store('arith_b')
    c.call('unsigned_divide')
    c.load('arith_rem')
    c.ops(Op.DUP)
    c.push(10)
    c.ops(Op.LTU)
    c.jz(alpha)
    c.push(ord('0'))
    c.ops(Op.ADD)
    c.jump(save)
    c.mark(alpha)
    c.push(ord('A') - 10)
    c.ops(Op.ADD)
    c.mark(save)
    c.push('digit_buffer')
    c.load('format_count')
    c.ops(Op.ADD, Op.BYTE_STORE)
    advance('format_count')
    c.load('arith_q')
    c.ops(Op.DUP)
    c.store('arith_a')
    c.jz(emit)
    c.jump(digits)
    c.mark(emit)
    advance('format_count', -1)
    c.push('digit_buffer')
    c.load('format_count')
    c.ops(Op.ADD, Op.BYTE_FETCH)
    c.call('raw_emit')
    c.load('format_count')
    c.jz(done)
    c.jump(emit)
    c.mark(done)
    c.ops(Op.NOP | 128)

    c.mark('print_signed')  # ( n -- ), raw, no trailing space.
    c.call('validate_base')
    positive = c.label('format_positive')
    c.ops(Op.DUP)
    c.push(0)
    c.ops(Op.LTS)
    c.jz(positive)
    output(b'-')
    c.negate()
    c.mark(positive)
    c.jump('print_unsigned')  # Tail jump shares the existing return frame.

    for name, routine in (('.', 'print_signed'), ('U.', 'print_unsigned')):
        def print_number(routine=routine):
            c.call(routine)
            output(b' ')
        word(name, 1, 0, print_number)

    def depth():
        c.load('depth')  # Guard already counted the result cell.
        c.push(1)
        c.ops(Op.SUB)
    word('DEPTH', 0, 1, depth)

    def stack_display():
        c.call('validate_base')
        c.load('depth')
        c.store('dump_count')
        set_cell('dump_index', 0)
        dump, dumped, restore, restored = (
            c.label('stack_' + x) for x in ('dump', 'dumped', 'restore', 'restored'))
        c.mark(dump)
        c.load('dump_index')
        c.load('dump_count')
        c.ops(Op.LTU)
        c.jz(dumped)
        c.push('stack_buffer')
        c.load('dump_index')
        c.ops(Op.SL, Op.ADD, Op.STORE)
        advance('dump_index')
        c.jump(dump)
        c.mark(dumped)
        output(b'<')
        c.load('dump_count')
        c.call('print_unsigned')
        output(b'> ')
        c.mark(restore)
        c.load('dump_index')
        c.jz(restored)
        advance('dump_index', -1)
        c.push('stack_buffer')
        c.load('dump_index')
        c.ops(Op.SL, Op.ADD, Op.FETCH, Op.DUP)
        c.call('print_signed')
        output(b' ')
        c.jump(restore)
        c.mark(restored)
    word('.S', 0, 0, stack_display)

    def words():
        c.load('latest')
        c.store('word_cursor')
        loop, visible, next_word, done = (
            c.label('words_' + x) for x in ('loop', 'visible', 'next', 'done'))
        c.mark(loop)
        c.load('word_cursor')
        c.jz(done)
        field('word_cursor', 2, byte=True)
        c.push(4)
        c.ops(Op.AND)
        c.jz(visible)
        c.jump(next_word)
        c.mark(visible)
        c.load('word_cursor')
        c.push(8)
        c.ops(Op.ADD)
        c.store('print_addr')
        field('word_cursor', 3, byte=True)
        c.store('print_left')
        c.call('print_span')
        output(b' ')
        c.mark(next_word)
        field('word_cursor', 0)
        c.store('word_cursor')
        c.jump(loop)
        c.mark(done)
        output(b'\r\n')
    word('WORDS', 0, 0, words)

    def abort():
        for name in ('depth', 'state', 'control_depth', 'definition_open',
                     'input_length', 'input_pos', 'token_addr', 'token_length'):
            set_cell(name, 0)
        c.jump('idle')
    word('ABORT', 0, 0, abort)

    # Entry from cold boot and non-returning errors/ABORT. No call frame here.
    c.mark('console_start')
    output(b'ok\r\n')
    c.mark('console_next')
    c.call('read_line')
    token, number, execute, line_done = (
        c.label('console_' + x) for x in ('token', 'number', 'execute', 'line_done'))
    c.mark(token)
    c.call('parse_name')
    c.load('token_length')
    c.jz(line_done)
    c.call('find_word')
    c.load('found_xt')
    c.jz(number)
    c.load('found_flags')
    c.push(2)
    c.ops(Op.AND)
    c.jz(execute)
    c.jump('error_compile_only')
    c.mark(execute)
    c.load('found_xt')
    c.ops(Op.CALL)  # Actual indirect invocation; no host dispatch.
    c.jump(token)
    c.mark(number)
    c.call('parse_number')
    c.load('number_status')
    valid_number = c.label('console_valid_number')
    c.jz('error_unknown')
    c.load('number_status')
    c.push(1)
    c.ops(Op.SUB)
    c.jz(valid_number)
    c.jump('error_number_overflow')
    c.mark(valid_number)
    c.guard(0, 1)
    c.load('number_value')
    c.jump(token)
    c.mark(line_done)
    output(b'ok\r\n')
    c.jump('console_next')
