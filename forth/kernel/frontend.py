"""Two bounded line editors feeding one interpreter; no interpreter reentry."""
from prim.isa import PrimOpcodes as Op
from forth.kernel.primitives import Code
from forth.kernel.interrupts import RINGS, RING_SIZE

FRONT_NAMES = ('poll_source', 'input_ring', 'input_byte', 'input_available',
               'input_failed', 'front_line', 'front_head', 'front_tail',
               'front_saved_owner', 'front_index', 'last_source',
               'console_initialized', 'front_char')
FRONT_VARIABLES = {name: 0xF060 + 2 * n for n, name in enumerate(FRONT_NAMES)}
LINES = (0xF200, 0xF300)
LENGTH, READY, ERROR, SKIP_LF, DISCARD, BUFFER = 0, 2, 4, 6, 8, 16


def emit_frontend(image):
    c = Code(image)

    def field(offset):
        c.load('front_line')
        if offset:
            c.push(offset)
            c.ops(Op.ADD)
        c.ops(Op.FETCH)

    def put(offset):  # ( value -- )
        c.load('front_line')
        if offset:
            c.push(offset)
            c.ops(Op.ADD)
        c.ops(Op.STORE)

    def constant(offset, value):
        c.push(value)
        put(offset)

    def echo(text):
        for byte in text:
            c.push(byte)
            c.call('front_echo')

    c.mark('frontend_start')
    initialized = c.label('front_initialized')
    c.load('console_initialized')
    c.jz(initialized)
    c.output(b'ok\r\n')  # Error/ABORT recovery prompt stays with its owner.
    c.ops(Op.NOP | 128)
    c.mark(initialized)
    for base in LINES:
        for offset in (LENGTH, READY, ERROR, SKIP_LF, DISCARD):
            c.push(0)
            c.push(base + offset)
            c.ops(Op.STORE)
    c.set_cell('last_source', 1)  # First tie selects UART; later ties alternate.
    c.call('vga_init')
    c.call('irq_init')  # Discard input that arrived before display initialization.
    for source in (1, 0):
        c.set_cell('console_owner', source)
        c.output(b'ok\r\n')
    c.set_cell('console_initialized', 1)
    c.ops(Op.NOP | 128)

    c.mark('front_echo')  # Preserve command ownership while echoing idle input.
    c.load('console_owner')
    c.store('front_saved_owner')
    c.load('poll_source')
    c.store('console_owner')
    c.call('raw_emit')
    c.load('front_saved_owner')
    c.store('console_owner')
    c.ops(Op.NOP | 128)

    c.mark('source_select')
    local, selected = c.label('source_local'), c.label('source_selected')
    c.load('poll_source')
    c.jz(local)
    c.set_cell('input_ring', RINGS['ps2'])
    c.set_cell('front_line', LINES[1])
    c.jump(selected)
    c.mark(local)
    c.set_cell('input_ring', RINGS['uart'])
    c.set_cell('front_line', LINES[0])
    c.mark(selected)
    c.ops(Op.NOP | 128)

    c.mark('source_recover')
    # Loss reset and head=tail must be atomic with respect to the ISR producer.
    c.ops(Op.INTDI)
    c.set_cell('input_failed', 0)
    c.load('input_ring')
    c.push(4)
    c.ops(Op.ADD, Op.FETCH)
    no_loss = c.label('source_no_loss')
    c.jz(no_loss)
    c.set_cell('input_failed', 1)
    c.push(0)
    c.load('input_ring')
    c.push(4)
    c.ops(Op.ADD, Op.STORE)
    c.load('input_ring')
    c.push(2)
    c.ops(Op.ADD, Op.FETCH)
    c.load('input_ring')
    c.ops(Op.STORE)  # Drop queued input; never execute a truncated command.
    for offset, value in ((LENGTH, 0), (READY, 0), (SKIP_LF, 0), (ERROR, 6), (DISCARD, 1)):
        constant(offset, value)
    c.load('poll_source')
    c.jz(no_loss)
    c.call('kbd_reset')
    c.mark(no_loss)
    c.ops(Op.INTEI | 128)

    c.mark('ring_take')
    c.set_cell('input_available', 0)
    c.load('input_ring')
    c.ops(Op.FETCH)
    c.store('front_head')
    c.load('input_ring')
    c.push(2)
    c.ops(Op.ADD, Op.FETCH)
    c.load('front_head')
    c.ops(Op.SUB)
    empty = c.label('ring_empty')
    c.jz(empty)
    c.load('input_ring')
    c.push(6)
    c.ops(Op.ADD)
    c.load('front_head')
    c.ops(Op.ADD, Op.BYTE_FETCH)
    c.store('input_byte')
    c.load('front_head')
    c.push(1)
    c.ops(Op.ADD)
    c.push(RING_SIZE - 1)
    c.ops(Op.AND)
    c.load('input_ring')
    c.ops(Op.STORE)
    c.set_cell('input_available', 1)
    c.mark(empty)
    c.ops(Op.NOP | 128)

    c.mark('source_read')
    c.call('source_select')
    c.call('source_recover')
    c.mark('source_read_ready')  # Source selected/recovered by caller or above.
    read, finish = c.label('source_read_byte'), c.label('source_read_finish')
    c.load('input_failed')
    c.jz(read)
    c.set_cell('input_available', 0)
    c.jump(finish)
    c.mark(read)
    c.call('ring_take')
    c.load('input_available')
    c.jz(finish)
    plain = c.label('source_plain_byte')
    c.load('poll_source')
    c.jz(plain)
    c.load('input_byte')
    c.store('kbd_scan')
    c.call('kbd_decode')
    c.load('kbd_char')
    c.store('input_byte')
    c.load('kbd_available')
    c.store('input_available')
    c.load('input_available')
    c.jz(finish)
    c.mark(plain)
    field(SKIP_LF)
    c.jz(finish)
    constant(SKIP_LF, 0)
    c.load('input_byte')
    c.push(10)
    c.ops(Op.SUB)
    not_lf = c.label('source_not_lf')
    c.jz(not_lf)
    c.jump(finish)
    c.mark(not_lf)
    c.set_cell('input_available', 0)
    c.mark(finish)
    c.ops(Op.NOP | 128)

    c.mark('raw_key')  # Blocking KEY reads ONLY its command's owner.
    key_loop, key_read, key_return = (c.label('key_' + n) for n in ('loop', 'read', 'return'))
    c.mark(key_loop)
    c.load('console_owner')
    c.store('poll_source')
    c.call('source_read')
    c.load('input_failed')
    c.jz(key_read)
    constant(ERROR, 0)  # Report now; resynchronizing EOL must not report twice.
    c.jump('error_input_overflow')
    c.mark(key_read)
    c.load('input_available')
    c.jz(key_loop)
    field(DISCARD)
    c.jz(key_return)
    # A previous lost line must be resynchronized before KEY may return data.
    c.load('input_byte')
    c.push(13)
    c.ops(Op.SUB)
    key_sync = c.label('key_resynchronized')
    c.jz(key_sync)
    c.load('input_byte')
    c.push(10)
    c.ops(Op.SUB)
    c.jz(key_sync)
    c.jump(key_loop)
    c.mark(key_sync)
    constant(DISCARD, 0)
    c.jump(key_loop)
    c.mark(key_return)
    c.load('input_byte')
    c.ops(Op.NOP | 128)

    c.mark('collect_source')
    c.call('source_select')
    c.call('source_recover')
    end = c.label('collect_end')
    field(READY)
    not_ready = c.label('collect_not_ready')
    c.jz(not_ready)
    c.jump(end)
    c.mark(not_ready)
    c.call('source_read_ready')
    c.load('input_available')
    c.jz(end)
    c.load('input_byte')
    c.store('front_char')
    cr, eol, edit, append = (c.label('collect_' + n) for n in ('cr', 'eol', 'edit', 'append'))
    for byte, label in ((13, cr), (10, eol)):
        c.load('front_char')
        c.push(byte)
        c.ops(Op.SUB)
        c.jz(label)
    field(DISCARD)
    accepted = c.label('collect_accepted')
    c.jz(accepted)
    c.jump(end)
    c.mark(accepted)
    field(ERROR)
    valid_line = c.label('collect_valid_line')
    c.jz(valid_line)
    c.jump(end)
    c.mark(valid_line)
    for byte in (8, 127):
        c.load('front_char')
        c.push(byte)
        c.ops(Op.SUB)
        c.jz(edit)
    c.load('front_char')
    c.push(32)
    c.ops(Op.LTU)
    c.jz(append)
    for byte in (9, 11, 12):
        c.load('front_char')
        c.push(byte)
        c.ops(Op.SUB)
        c.jz(append)
    constant(ERROR, 9)
    c.jump(end)
    c.mark(edit)
    field(LENGTH)
    c.jz(end)
    field(LENGTH)
    c.push(1)
    c.ops(Op.SUB)
    put(LENGTH)
    echo(b'\b \b')
    c.jump(end)
    c.mark(append)
    field(LENGTH)
    c.push(127)
    c.ops(Op.LTU)
    full = c.label('collect_full')
    c.jz(full)
    c.load('front_char')
    c.load('front_line')
    c.push(BUFFER)
    c.ops(Op.ADD)
    field(LENGTH)
    c.ops(Op.ADD, Op.BYTE_STORE)
    field(LENGTH)
    c.push(1)
    c.ops(Op.ADD)
    put(LENGTH)
    c.load('front_char')
    c.call('front_echo')
    c.jump(end)
    c.mark(full)
    constant(ERROR, 6)
    c.jump(end)
    c.mark(cr)
    constant(SKIP_LF, 1)
    c.mark(eol)
    # A KEY loss already reported synchronizes silently on its next EOL.
    ordinary_eol = c.label('collect_ordinary_eol')
    field(DISCARD)
    c.jz(ordinary_eol)
    constant(DISCARD, 0)
    field(ERROR)
    c.jz(end)
    c.mark(ordinary_eol)
    echo(b'\r\n')
    constant(READY, 1)
    c.mark(end)
    c.ops(Op.NOP | 128)

    c.mark('read_line')
    loop = c.label('front_collect')
    c.mark(loop)
    for source in (0, 1):
        c.set_cell('poll_source', source)
        c.call('collect_source')
    unlocked, choose = c.label('front_unlocked'), c.label('front_choose')
    c.load('definition_open')
    c.jz(unlocked)
    c.load('console_owner')
    c.store('poll_source')
    c.jump(choose)
    c.mark(unlocked)
    c.load('last_source')
    c.push(1)
    c.ops(Op.XOR)
    c.store('poll_source')
    c.mark(choose)
    c.call('source_select')
    field(READY)
    try_other, selected_line, wait = (c.label('front_' + n) for n in ('try_other', 'selected', 'wait'))
    c.jz(try_other)
    c.jump(selected_line)
    c.mark(try_other)
    c.load('definition_open')
    no_lock = c.label('front_no_lock')
    c.jz(no_lock)
    c.jump(wait)
    c.mark(no_lock)
    c.load('poll_source')
    c.push(1)
    c.ops(Op.XOR)
    c.store('poll_source')
    c.call('source_select')
    field(READY)
    c.jz(wait)
    c.jump(selected_line)
    c.mark(wait)
    c.call('irq_wait')
    c.jump(loop)
    c.mark(selected_line)
    c.load('poll_source')
    c.store('console_owner')
    c.load('poll_source')
    c.store('last_source')
    field(LENGTH)
    c.store('input_length')
    field(ERROR)
    c.store('line_error')
    for name in ('input_pos', 'token_addr', 'token_length', 'front_index'):
        c.set_cell(name, 0)
    copy, copied = c.label('front_copy'), c.label('front_copied')
    c.mark(copy)
    c.load('front_index')
    c.load('input_length')
    c.ops(Op.LTU)
    c.jz(copied)
    c.load('front_line')
    c.push(BUFFER)
    c.ops(Op.ADD)
    c.load('front_index')
    c.ops(Op.ADD, Op.BYTE_FETCH)
    c.push('input_buffer')
    c.load('front_index')
    c.ops(Op.ADD, Op.BYTE_STORE)
    c.advance('front_index')
    c.jump(copy)
    c.mark(copied)
    c.push(0)
    c.push('input_buffer')
    c.load('input_length')
    c.ops(Op.ADD, Op.BYTE_STORE)
    for offset in (LENGTH, READY, ERROR):
        constant(offset, 0)
    c.load('line_error')
    okay = c.label('front_line_okay')
    c.jz(okay)
    c.load('line_error')
    c.push(6)
    c.ops(Op.SUB)
    c.jz('error_input_overflow')
    c.jump('error_input_character')
    c.mark(okay)
    c.ops(Op.NOP | 128)
