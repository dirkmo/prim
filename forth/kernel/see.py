"""Bounded, non-executing native-code inspection of completed user words."""
from prim.isa import PrimOpcodes as Op
from forth.kernel.primitives import Code, emit_word

SEE_NAMES = ('see_pc', 'see_start', 'see_end', 'see_scan', 'see_op', 'see_ret',
             'see_value', 'see_next', 'see_follow', 'see_data', 'see_hex_value')


def emit_see(image):
    c = Code(image)

    def field(name, offset=0, byte=False):
        c.load(name)
        if offset:
            c.push(offset)
            c.ops(Op.ADD)
        c.ops(Op.BYTE_FETCH if byte else Op.FETCH)

    def equals(name, value, label):
        c.load(name)
        c.push(value)
        c.ops(Op.SUB)
        c.jz(label)

    def line():
        c.output(b'  ')
        c.load('see_pc')
        c.call('see_hex')
        c.output(b': ')

    def cr():
        c.output(b'\r\n')

    # Raw helpers use private scratch and do not touch logical DEPTH or BASE.
    c.mark('see_hex')  # ( u -- ), fixed four hexadecimal digits.
    c.store('see_hex_value')
    c.output(b'$')
    for shift in (12, 8, 4, 0):
        c.load('see_hex_value')
        c.ops(*([Op.SR] * shift))
        c.push(15)
        c.ops(Op.AND, Op.DUP)
        c.push(10)
        c.ops(Op.LTU)
        alpha, emit = c.label('see_hex_alpha'), c.label('see_hex_emit')
        c.jz(alpha)
        c.push(48)
        c.ops(Op.ADD)
        c.jump(emit)
        c.mark(alpha)
        c.push(55)
        c.ops(Op.ADD)
        c.mark(emit)
        c.call('raw_emit')
    c.ops(Op.NOP | 128)

    c.mark('see_name')  # see_value is an XT; resolve by address, including shadows.
    c.load('latest')
    c.store('see_scan')
    scan, found, missing = (c.label('see_name_' + n)
                            for n in ('scan', 'found', 'missing'))
    c.mark(scan)
    c.load('see_scan')
    c.jz(missing)
    field('see_scan', 4)
    c.load('see_value')
    c.ops(Op.SUB)
    c.jz(found)
    field('see_scan')
    c.store('see_scan')
    c.jump(scan)
    c.mark(found)
    c.load('see_scan')
    c.push(6)
    c.ops(Op.ADD)
    c.store('print_addr')
    field('see_scan', 3, byte=True)
    c.store('print_left')
    c.jump('print_span')
    c.mark(missing)
    c.load('see_value')
    c.jump('see_hex')

    # Recognize the compiler's string-data jump without following arbitrary
    # forward branches. Returns through see_data (zero, or start of byte span).
    c.mark('see_string')
    c.set_cell('see_data', 0)
    done = c.label('see_string_done')
    # Target must follow this jump and leave at least a PUSH16 operand in bounds.
    c.load('see_next')
    c.load('see_value')
    c.ops(Op.LTU)
    c.jz(done)
    c.load('see_end')
    c.push(3)
    c.ops(Op.SUB)
    c.load('see_value')
    c.ops(Op.LTU)
    room, push = c.label('see_string_room'), c.label('see_string_push')
    c.jz(room)
    c.jump(done)
    c.mark(room)
    field('see_value', byte=True)
    c.push(Op.PUSH)
    c.ops(Op.SUB)
    c.jz(push)
    c.jump(done)
    c.mark(push)
    field('see_value', 1)
    c.load('see_next')
    c.ops(Op.SUB)
    direct, indirect = c.label('see_string_direct'), c.label('see_string_indirect')
    c.jz(direct)
    # S" starts with the literal-depth prefix and a PUSH16 of the string address.
    field('see_value', 1)
    c.push('literal_depth')
    c.ops(Op.SUB)
    c.jz(indirect)
    c.jump(done)
    c.mark(indirect)
    c.load('see_end')
    c.push(7)
    c.ops(Op.SUB)
    c.load('see_value')
    c.ops(Op.LTU)
    enough = c.label('see_string_enough')
    c.jz(enough)
    c.jump(done)
    c.mark(enough)
    for offset, opcode in ((3, Op.CALL), (4, Op.PUSH)):
        field('see_value', offset, byte=True)
        c.push(opcode)
        c.ops(Op.SUB)
        valid = c.label('see_string_valid')
        c.jz(valid)
        c.jump(done)
        c.mark(valid)
    field('see_value', 5)
    c.load('see_next')
    c.ops(Op.SUB)
    c.jz(direct)
    c.jump(done)
    c.mark(direct)
    c.load('see_next')
    c.store('see_data')
    c.mark(done)
    c.ops(Op.NOP | 128)

    def see():
        closed = c.label('see_closed')
        c.load('definition_open')
        c.jz(closed)
        c.jump('error_compiler')
        c.mark(closed)
        c.call('lookup_next_xt')
        c.load('found_header')
        c.push('user_start')
        c.ops(Op.LTU)
        user = c.label('see_user')
        c.jz(user)
        c.jump('error_see')
        c.mark(user)
        c.load('here')
        c.store('see_end')
        c.load('latest')
        c.store('see_scan')
        bound, bounded = c.label('see_bound'), c.label('see_bounded')
        c.mark(bound)
        c.load('see_scan')
        c.load('found_header')
        c.ops(Op.SUB)
        c.jz(bounded)
        c.load('see_scan')
        c.store('see_end')
        field('see_scan')
        c.store('see_scan')
        c.jump(bound)
        c.mark(bounded)
        c.load('found_xt')
        c.push('user_start')
        c.ops(Op.LTU)
        valid_xt = c.label('see_valid_xt')
        c.jz(valid_xt)
        c.jump('error_see')
        c.mark(valid_xt)
        c.load('found_xt')
        c.load('see_end')
        c.ops(Op.LTU)
        c.jz('error_see')
        c.load('found_xt')
        c.store('see_start')
        c.load('found_xt')
        c.store('see_pc')
        c.output(b': ')
        c.load('found_xt')
        c.store('see_value')
        c.call('see_name')
        cr()

        loop, done, byte, push8, push16, operand, fits, literal, pair = (
            c.label('see_' + n) for n in ('loop', 'done', 'byte', 'push8', 'push16',
                                          'operand', 'fits', 'literal', 'pair'))
        call, jump, conditional, rendered, next_instruction = (
            c.label('see_' + n) for n in ('call', 'jump', 'conditional', 'rendered', 'next'))
        c.mark(loop)
        c.load('see_pc')
        c.load('see_end')
        c.ops(Op.LTU)
        c.jz(done)
        field('see_pc', byte=True)
        c.ops(Op.DUP)
        c.push(128)
        c.ops(Op.AND)
        c.store('see_ret')
        c.push(127)
        c.ops(Op.AND)
        c.store('see_op')
        c.load('see_pc')
        c.push(1)
        c.ops(Op.ADD)
        c.store('see_next')
        equals('see_op', Op.PUSH8, push8)
        equals('see_op', Op.PUSH, push16)
        c.jump(byte)
        c.mark(push8)
        c.advance('see_next')
        c.jump(operand)
        c.mark(push16)
        c.advance('see_next', 2)
        c.mark(operand)
        c.load('see_end')
        c.load('see_next')
        c.ops(Op.LTU)
        c.jz(fits)
        # Truncated operands are bytes, never read beyond the selected word.
        c.load('see_pc')
        c.push(1)
        c.ops(Op.ADD)
        c.store('see_next')
        c.jump(byte)
        c.mark(fits)
        wide, value = c.label('see_wide'), c.label('see_value')
        equals('see_op', Op.PUSH, wide)
        field('see_pc', 1, byte=True)
        c.jump(value)
        c.mark(wide)
        field('see_pc', 1)
        c.mark(value)
        c.store('see_value')
        c.load('see_ret')
        c.jz(pair)
        c.jump(literal)
        c.mark(pair)
        c.load('see_next')
        c.load('see_end')
        c.ops(Op.LTU)
        c.jz(literal)
        field('see_next', byte=True)
        c.store('see_follow')
        equals('see_follow', Op.CALL, call)
        equals('see_follow', Op.JP, jump)
        equals('see_follow', Op.JZ, conditional)
        c.jump(literal)
        c.mark(call)
        bookkeeping = c.label('see_bookkeeping')
        for helper in ('literal_depth', 'branch_depth'):
            equals('see_value', helper, bookkeeping)
        line()
        c.output(b'CALL ')
        c.call('see_name')
        c.advance('see_next')
        c.jump(rendered)
        c.mark(bookkeeping)
        c.advance('see_next')
        c.jump(next_instruction)
        c.mark(conditional)
        line()
        c.output(b'0BRANCH ')
        c.load('see_value')
        c.call('see_hex')
        c.advance('see_next')
        c.jump(rendered)
        c.mark(jump)
        c.advance('see_next')
        internal = c.label('see_internal')
        c.load('see_value')
        c.load('see_start')
        c.ops(Op.LTU)
        tail = c.label('see_tail')
        c.jz(internal)
        c.jump(tail)
        c.mark(internal)
        c.load('see_value')
        c.load('see_end')
        c.ops(Op.LTU)
        branch = c.label('see_branch')
        c.jz(tail)
        c.mark(branch)
        line()
        c.output(b'BRANCH ')
        c.load('see_value')
        c.call('see_hex')
        cr()
        c.call('see_string')
        c.load('see_data')
        c.jz(next_instruction)
        c.output(b'    DATA "')
        c.load('see_data')
        c.store('print_addr')
        c.load('see_value')
        c.load('see_data')
        c.ops(Op.SUB)
        c.store('print_left')
        c.call('print_span')
        c.output(b'"\r\n')
        c.load('see_value')
        c.store('see_next')
        c.jump(next_instruction)
        c.mark(tail)
        line()
        c.output(b'TAIL ')
        c.call('see_name')
        c.output(b' ;\r\n')
        c.jump(done)
        c.mark(literal)
        line()
        c.output(b'LIT ')
        c.load('see_value')
        c.call('print_unsigned')
        c.jump(rendered)
        c.mark(byte)
        line()
        nop = c.label('see_nop')
        equals('see_op', Op.NOP, nop)
        c.output(b'.BYTE ')
        field('see_pc', byte=True)
        c.call('see_hex')
        c.jump(rendered)
        c.mark(nop)
        # A terminal NOP is the normal return of an empty/unfolded word.
        c.output(b'NOP')
        c.mark(rendered)
        continued = c.label('see_continued')
        c.load('see_ret')
        c.jz(continued)
        c.output(b' ;\r\n')
        c.jump(done)
        c.mark(continued)
        cr()
        c.mark(next_instruction)
        c.load('see_next')
        c.store('see_pc')
        c.jump(loop)
        c.mark(done)
    emit_word(c, 'SEE', 0, 0, see, flags=1)
