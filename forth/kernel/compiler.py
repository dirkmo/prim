"""AP 6: transactional native-code compiler, executed entirely on Prim."""
from functools import partial
from prim.isa import PrimOpcodes as Op
from forth.kernel.primitives import Code, emit_word


def emit_compiler(image):
    c = Code(image)
    word = partial(emit_word, c)

    def set_cell(name, value):
        c.push(value)
        c.store(name)

    def advance(name, amount=1):
        c.load(name)
        c.push(amount)
        c.ops(Op.ADD)
        c.store(name)

    def byte(value):
        c.push(value)
        c.call('compile_byte')

    def cell(value):
        c.push(value)
        c.call('compile_cell')

    def align():
        aligned = c.label('compiler_aligned')
        c.load('here')
        c.push(1)
        c.ops(Op.AND)
        c.jz(aligned)
        byte(0)
        c.mark(aligned)

    def record(kind):
        set_cell('last_kind', kind)
        c.load('here')
        c.store('last_end')

    c.mark('rollback_definition')  # ( -- ), no arbitrary immediate side effects rolled back.
    done = c.label('rollback_done')
    c.load('definition_open')
    c.jz(done)
    for source, target in (('saved_here', 'here'), ('saved_latest', 'latest')):
        c.load(source)
        c.store(target)
    for name in ('definition_open', 'pending_header', 'state', 'control_depth',
                 'fold_safe', 'last_opcode', 'last_end', 'last_kind'):
        set_cell(name, 0)
    c.mark(done)
    c.ops(Op.NOP | 128)

    c.mark('require_compiling')
    c.load('definition_open')
    c.jz('error_compiler')
    c.load('state')
    c.push(1)
    c.ops(Op.SUB)
    good = c.label('compiling_ok')
    c.jz(good)
    c.jump('error_compiler')
    c.mark(good)
    c.ops(Op.NOP | 128)

    # Validate HERE and space without overflowing 16-bit address arithmetic.
    c.mark('compiler_reserve')  # ( -- ), required byte count in compiler_needed.
    lower, upper, room = (c.label('reserve_' + x) for x in ('lower', 'upper', 'room'))
    c.load('here')
    c.push('user_start')
    c.ops(Op.LTU)
    c.jz(lower)
    c.jump('error_memory')
    c.mark(lower)
    c.push('user_limit')
    c.load('here')
    c.ops(Op.LTU)
    c.jz(upper)
    c.jump('error_memory')
    c.mark(upper)
    c.push('user_limit')
    c.load('here')
    c.ops(Op.SUB)
    c.load('compiler_needed')
    c.ops(Op.LTU)
    c.jz(room)
    c.jump('error_memory')
    c.mark(room)
    c.ops(Op.NOP | 128)

    for label, size, opcode in (('compile_byte', 1, Op.BYTE_STORE),
                                ('compile_cell', 2, Op.STORE)):
        c.mark(label)  # ( value -- ), raw, bounds checked before writing.
        c.store('emit_value')
        set_cell('compiler_needed', size)
        c.call('compiler_reserve')
        c.load('emit_value')
        c.load('here')
        c.ops(opcode)
        advance('here', size)
        c.ops(Op.NOP | 128)

    # The compiled guard runs BEFORE the literal PUSH, with no user result yet.
    c.mark('literal_guard')
    c.guard(0, 1)
    c.ops(Op.NOP | 128)

    c.mark('compile_word')  # ( -- ), found_xt -> PUSH16 xt; CALL.
    set_cell('compiler_needed', 4)
    c.call('compiler_reserve')
    byte(Op.PUSH)
    c.load('found_xt')
    c.call('compile_cell')
    c.load('here')
    c.store('last_opcode')
    byte(Op.CALL)
    record(1)
    c.ops(Op.NOP | 128)

    c.mark('compile_literal')  # ( -- ), compile_value -> guard call; PUSH8/16.
    large, prefix, small_value, finished = (
        c.label('literal_' + x) for x in ('large', 'prefix', 'small_value', 'finished'))
    c.load('compile_value')
    c.push(256)
    c.ops(Op.LTU)
    c.jz(large)
    set_cell('compiler_needed', 6)
    c.jump(prefix)
    c.mark(large)
    set_cell('compiler_needed', 7)
    c.mark(prefix)
    c.call('compiler_reserve')
    byte(Op.PUSH)
    cell('literal_guard')
    byte(Op.CALL)
    c.load('here')
    c.store('last_opcode')
    c.load('compile_value')
    c.push(256)
    c.ops(Op.LTU)
    c.jz(small_value)
    byte(Op.PUSH8)
    c.load('compile_value')
    c.call('compile_byte')
    c.jump(finished)
    c.mark(small_value)
    byte(Op.PUSH)
    c.load('compile_value')
    c.call('compile_cell')
    c.mark(finished)
    record(2)
    c.ops(Op.NOP | 128)

    c.mark('lookup_next_xt')  # ( -- ), parser moves past the next name, result in found_xt.
    c.call('parse_name')
    c.load('token_length')
    c.jz('error_name')
    c.call('find_word')
    c.load('found_xt')
    c.jz('error_unknown')
    c.ops(Op.NOP | 128)

    def colon():
        closed = c.label('colon_closed')
        c.load('definition_open')
        c.jz(closed)
        c.jump('error_compiler')
        c.mark(closed)
        c.call('parse_name')
        c.load('token_length')
        c.jz('error_name')
        c.load('token_length')
        c.push(32)
        c.ops(Op.LTU)
        c.jz('error_name')
        for source, target in (('here', 'saved_here'), ('latest', 'saved_latest')):
            c.load(source)
            c.store(target)
        set_cell('definition_open', 1)
        # Alignment + padded header + at least one return byte, in one check.
        c.load('token_length')
        c.push(9)
        c.ops(Op.ADD)
        c.push(0xFFFE)
        c.ops(Op.AND)
        c.load('here')
        c.push(1)
        c.ops(Op.AND, Op.ADD)
        c.push(1)
        c.ops(Op.ADD)
        c.store('compiler_needed')
        c.call('compiler_reserve')
        align()
        c.load('here')
        c.store('pending_header')
        c.load('latest')
        c.call('compile_cell')
        byte(4)  # HIDDEN until successful semicolon.
        c.load('token_length')
        c.call('compile_byte')
        cell(0)  # XT patched after the name is copied and padded.
        cell(0)  # Call class, no inline opcode.
        set_cell('compiler_index', 0)
        loop, copied = c.label('name_copy'), c.label('name_copied')
        c.mark(loop)
        c.load('compiler_index')
        c.load('token_length')
        c.ops(Op.LTU)
        c.jz(copied)
        c.load('token_addr')
        c.load('compiler_index')
        c.ops(Op.ADD, Op.BYTE_FETCH)
        c.call('compile_byte')
        advance('compiler_index')
        c.jump(loop)
        c.mark(copied)
        align()
        c.load('here')
        c.load('pending_header')
        c.push(4)
        c.ops(Op.ADD, Op.STORE)
        c.load('pending_header')
        c.store('latest')
        for name, value in (('state', 1), ('fold_safe', 1), ('control_depth', 0),
                            ('last_opcode', 0), ('last_end', 0), ('last_kind', 0)):
            set_cell(name, value)
    # Immediate so a nested colon is rejected instead of silently compiled.
    word(':', 0, 0, colon, flags=1)

    def semicolon():
        c.call('require_compiling')
        c.load('control_depth')
        resolved = c.label('control_resolved')
        c.jz(resolved)
        c.jump('error_control')
        c.mark(resolved)
        fallback, call, literal, publish = (
            c.label('finish_' + x) for x in ('fallback', 'call', 'literal', 'publish'))
        c.load('fold_safe')
        c.jz(fallback)
        c.load('last_end')
        c.load('here')
        c.ops(Op.SUB)
        same_end = c.label('finish_same_end')
        c.jz(same_end)
        c.jump(fallback)
        c.mark(same_end)
        # The remembered opcode must belong to this definition's code body.
        c.load('last_opcode')
        c.load('pending_header')
        c.push(4)
        c.ops(Op.ADD, Op.FETCH, Op.LTU)
        inside = c.label('finish_inside_body')
        c.jz(inside)
        c.jump(fallback)
        c.mark(inside)
        c.load('last_opcode')
        c.load('here')
        c.ops(Op.LTU)
        c.jz(fallback)
        c.load('last_kind')
        c.push(1)
        c.ops(Op.SUB)
        c.jz(call)
        c.load('last_kind')
        c.push(2)
        c.ops(Op.SUB)
        c.jz(literal)
        c.jump(fallback)
        c.mark(call)
        c.load('last_opcode')
        c.ops(Op.BYTE_FETCH)
        c.push(Op.CALL)
        c.ops(Op.SUB)
        valid_call = c.label('finish_valid_call')
        c.jz(valid_call)
        c.jump(fallback)
        c.mark(valid_call)
        c.push(Op.JP)
        c.load('last_opcode')
        c.ops(Op.BYTE_STORE)
        c.jump(publish)
        c.mark(literal)
        c.load('last_opcode')
        c.ops(Op.BYTE_FETCH, Op.DUP)
        c.push(Op.PUSH8)
        c.ops(Op.SUB)
        valid_literal = c.label('finish_valid_literal')
        c.jz(valid_literal)
        c.ops(Op.DUP)
        c.push(Op.PUSH)
        c.ops(Op.SUB)
        c.jz(valid_literal)
        c.ops(Op.DROP)
        c.jump(fallback)
        c.mark(valid_literal)
        c.push(128)
        c.ops(Op.OR)
        c.load('last_opcode')
        c.ops(Op.BYTE_STORE)
        c.jump(publish)
        c.mark(fallback)
        byte(Op.NOP | 128)
        c.mark(publish)
        c.load('pending_header')
        c.push(2)
        c.ops(Op.ADD, Op.DUP, Op.BYTE_FETCH)
        c.push(0xFB)
        c.ops(Op.AND, Op.SWAP, Op.BYTE_STORE)
        for name in ('state', 'definition_open', 'pending_header', 'fold_safe', 'last_kind'):
            set_cell(name, 0)
    word(';', 0, 0, semicolon, flags=3)
    image.define('semicolon_xt', image.symbols[image.words[-1]['xt']])

    word('STATE', 0, 1, lambda: c.push('state'))

    def immediate():
        closed = c.label('immediate_closed')
        c.load('definition_open')
        c.jz(closed)
        c.jump('error_compiler')
        c.mark(closed)
        c.load('latest')
        c.push('user_start')
        c.ops(Op.LTU)
        valid = c.label('immediate_user')
        c.jz(valid)
        c.jump('error_immediate')
        c.mark(valid)
        c.load('latest')
        c.push(2)
        c.ops(Op.ADD, Op.DUP, Op.BYTE_FETCH)
        c.push(1)
        c.ops(Op.OR, Op.SWAP, Op.BYTE_STORE)
    word('IMMEDIATE', 0, 0, immediate)

    def bracket_open():
        c.call('require_compiling')
        set_cell('state', 0)
        set_cell('fold_safe', 0)
    word('[', 0, 0, bracket_open, flags=3)

    def bracket_close():
        c.load('definition_open')
        c.jz('error_compiler')
        set_cell('state', 1)
        set_cell('fold_safe', 0)
    word(']', 0, 0, bracket_close, flags=1)

    def literal_word():
        c.call('require_compiling')
        c.store('compile_value')
        c.call('compile_literal')
    word('LITERAL', 1, 0, literal_word, flags=3)

    def tick():
        c.call('lookup_next_xt')
        c.load('found_xt')
    word("'", 0, 1, tick)

    def bracket_tick():
        c.call('require_compiling')
        c.call('lookup_next_xt')
        c.load('found_xt')
        c.store('compile_value')
        c.call('compile_literal')
    word("[']", 0, 0, bracket_tick, flags=3)
    word('EXECUTE', 1, 0, lambda: c.ops(Op.JP))  # Tail invocation using caller's frame.
