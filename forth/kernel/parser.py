"""AP 4: on-CPU line input, token parsing and bounded integer conversion."""
from functools import partial
from prim.isa import PrimOpcodes as Op
from forth.kernel.primitives import Code, emit_word


def emit_parser(image):
    c = Code(image)
    word = partial(emit_word, c)

    def set_cell(name, value):
        c.push(value)
        c.store(name)

    def advance(name, amount=1):
        c.load(name)
        c.push(abs(amount))
        c.ops(Op.ADD if amount > 0 else Op.SUB)
        c.store(name)

    def char_at(position):
        c.load(position)
        c.ops(Op.BYTE_FETCH)

    def buffer_char():
        c.push('input_buffer')
        c.load('input_pos')
        c.ops(Op.ADD, Op.BYTE_FETCH)

    def output(text):
        for byte in text:
            c.push(byte)
            c.push('uart_data')
            c.ops(Op.BYTE_STORE)

    def char_equals(value, target):
        c.load('io_char')
        c.push(value)
        c.ops(Op.SUB)
        c.jz(target)

    # Raw private I/O does not touch the logical user DEPTH.
    c.mark('raw_key')
    poll = c.label('raw_key_poll')
    c.mark(poll)
    c.push('uart_csr')
    c.ops(Op.BYTE_FETCH)
    c.push(1)
    c.ops(Op.AND)
    c.jz(poll)
    c.push('uart_data')
    c.ops(Op.BYTE_FETCH, Op.NOP | 128)

    c.mark('raw_emit')
    c.push('uart_data')
    c.ops(Op.BYTE_STORE, Op.NOP | 128)

    # ( char -- flag ): ASCII whitespace is 09..0D or 20.
    c.mark('is_space')
    yes, upper = c.label('space_yes'), c.label('space_upper')
    c.ops(Op.DUP)
    c.push(32)
    c.ops(Op.SUB)
    c.jz(yes)
    c.ops(Op.DUP)
    c.push(9)
    c.ops(Op.LTU)
    c.jz(upper)
    c.ops(Op.DROP)
    c.push(0)
    c.ops(Op.NOP | 128)
    c.mark(upper)
    c.push(14)
    c.ops(Op.LTU, Op.NOP | 128)
    c.mark(yes)
    c.ops(Op.DROP)
    c.push(65535)
    c.ops(Op.NOP | 128)

    c.mark('read_line')  # ( -- ); preserves all user cells.
    for name in ('input_length', 'input_pos', 'token_addr', 'token_length', 'line_error'):
        set_cell(name, 0)
    c.push(0)
    c.push('input_buffer')
    c.ops(Op.BYTE_STORE)
    loop, regular, cr, eol, edit, append = (
        c.label('line_' + name) for name in ('loop', 'regular', 'cr', 'eol', 'edit', 'append'))
    c.mark(loop)
    c.call('raw_key')
    c.store('io_char')
    c.load('skip_lf')
    c.jz(regular)
    set_cell('skip_lf', 0)
    char_equals(10, loop)
    c.mark(regular)
    char_equals(13, cr)
    char_equals(10, eol)
    c.load('line_error')
    accept = c.label('line_accept')
    c.jz(accept)
    c.jump(loop)  # Once invalid, drain the complete line; edits cannot undo it.
    c.mark(accept)
    char_equals(8, edit)
    char_equals(127, edit)
    c.load('io_char')
    c.push(32)
    c.ops(Op.LTU)
    c.jz(append)
    for byte in (9, 11, 12):
        char_equals(byte, append)
    set_cell('line_error', 9)
    c.jump(loop)
    c.mark(edit)
    c.load('input_length')
    c.jz(loop)
    advance('input_length', -1)
    c.push(0)
    c.push('input_buffer')
    c.load('input_length')
    c.ops(Op.ADD, Op.BYTE_STORE)
    output(b'\b \b')
    c.jump(loop)
    c.mark(append)
    c.load('input_length')
    c.push(127)
    c.ops(Op.LTU)
    room = c.label('line_room')
    c.jz(room)
    c.load('io_char')
    c.push('input_buffer')
    c.load('input_length')
    c.ops(Op.ADD, Op.BYTE_STORE)
    advance('input_length')
    c.push(0)
    c.push('input_buffer')
    c.load('input_length')
    c.ops(Op.ADD, Op.BYTE_STORE)
    c.load('io_char')
    c.call('raw_emit')
    c.jump(loop)
    c.mark(room)
    set_cell('line_error', 6)
    c.jump(loop)
    c.mark(cr)
    set_cell('skip_lf', 1)
    c.mark(eol)
    output(b'\r\n')
    c.load('line_error')
    done = c.label('line_done')
    c.jz(done)
    c.load('line_error')
    c.push(6)
    c.ops(Op.SUB)
    c.jz('error_input_overflow')
    c.jump('error_input_character')
    c.mark(done)
    c.ops(Op.NOP | 128)

    # parse_name consumes exactly one terminating delimiter, if present.
    # Tokens may be 127 bytes; dictionary names are limited separately to 31.
    c.mark('parse_name')  # ( -- ); token_addr/token_length, or length zero at EOF.
    set_cell('token_length', 0)
    set_cell('token_addr', 0)
    skip, scan, found, finish, delimiter = (
        c.label('token_' + x) for x in ('skip', 'scan', 'found', 'finish', 'delimiter'))
    c.mark(skip)
    c.load('input_pos')
    c.load('input_length')
    c.ops(Op.LTU)
    c.jz(finish)
    buffer_char()
    c.call('is_space')
    c.jz(found)
    advance('input_pos')
    c.jump(skip)
    c.mark(found)
    c.push('input_buffer')
    c.load('input_pos')
    c.ops(Op.ADD)
    c.store('token_addr')
    c.mark(scan)
    c.load('input_pos')
    c.load('input_length')
    c.ops(Op.LTU)
    c.jz(finish)
    buffer_char()
    c.call('is_space')
    text = c.label('token_text')
    c.jz(text)
    c.jump(delimiter)
    c.mark(text)
    advance('token_length')
    advance('input_pos')
    c.jump(scan)
    c.mark(delimiter)
    advance('input_pos')
    c.mark(finish)
    c.ops(Op.NOP | 128)

    c.mark('skip_line')
    c.load('input_length')
    c.store('input_pos')
    c.ops(Op.NOP | 128)

    c.mark('skip_paren')
    loop, close = c.label('comment_loop'), c.label('comment_close')
    c.mark(loop)
    c.load('input_pos')
    c.load('input_length')
    c.ops(Op.LTU)
    c.jz('error_comment')
    buffer_char()
    c.push(ord(')'))
    c.ops(Op.SUB)
    c.jz(close)
    advance('input_pos')
    c.jump(loop)
    c.mark(close)
    advance('input_pos')
    c.ops(Op.NOP | 128)

    # Kernel-only number conversion: no user stack effect. status=0 syntax/
    # unknown token, 1 success, 2 overflow. Invalid BASE is a nonreturning error.
    c.mark('parse_number')
    for name in ('number_value', 'number_status', 'number_acc',
                 'number_negative', 'number_overflow'):
        set_cell(name, 0)
    c.load('base')
    c.ops(Op.DUP)
    c.push(2)
    c.ops(Op.LTU)
    lower = c.label('base_lower_ok')
    c.jz(lower)
    c.ops(Op.DROP)
    c.jump('error_base')
    c.mark(lower)
    c.push(37)
    c.ops(Op.LTU)
    c.jz('error_base')
    c.load('base')
    c.store('number_base')
    c.load('token_addr')
    c.store('number_pos')
    c.load('token_length')
    c.store('number_left')
    end = c.label('number_return')
    c.load('number_left')
    c.jz(end)
    char_at('number_pos')
    c.store('io_char')
    negative, sign, prefix, hex_prefix, decimal_prefix, prefixed, digits = (
        c.label('number_' + name) for name in
        ('negative', 'sign', 'prefix', 'hex_prefix', 'decimal_prefix', 'prefixed', 'digits'))
    char_equals(ord('-'), negative)
    char_equals(ord('+'), sign)
    c.jump(prefix)
    c.mark(negative)
    set_cell('number_negative', 1)
    c.mark(sign)
    advance('number_pos')
    advance('number_left', -1)
    c.load('number_left')
    c.jz(end)
    c.mark(prefix)
    char_at('number_pos')
    c.store('io_char')
    char_equals(ord('$'), hex_prefix)
    char_equals(ord('#'), decimal_prefix)
    c.jump(digits)
    c.mark(hex_prefix)
    set_cell('number_base', 16)
    c.jump(prefixed)
    c.mark(decimal_prefix)
    set_cell('number_base', 10)
    c.mark(prefixed)
    advance('number_pos')
    advance('number_left', -1)
    c.load('number_left')
    c.jz(end)

    c.mark(digits)
    char_at('number_pos')
    c.store('io_char')
    c.load('io_char')
    c.push(ord('0'))
    c.ops(Op.SUB, Op.DUP)
    c.push(10)
    c.ops(Op.LTU)
    alpha, converted, invalid_digit = (c.label('digit_' + x)
                                       for x in ('alpha', 'converted', 'invalid'))
    c.jz(alpha)
    c.jump(converted)
    c.mark(alpha)
    c.ops(Op.DROP)
    c.load('io_char')
    c.push(32)
    c.ops(Op.OR)
    c.push(ord('a'))
    c.ops(Op.SUB, Op.DUP)
    c.push(26)
    c.ops(Op.LTU)
    c.jz(invalid_digit)
    c.push(10)
    c.ops(Op.ADD)
    c.mark(converted)
    c.store('number_digit')
    c.load('number_digit')
    c.load('number_base')
    c.ops(Op.LTU)
    c.jz(end)
    # Bounded repeated addition, at most 36 iterations per input digit.
    # Carry is checked before count arithmetic can overwrite it.
    set_cell('number_sum', 0)
    c.load('number_base')
    c.store('number_count')
    multiply, multiplied, no_carry, digit_no_carry, finished, overflow, success = (
        c.label('number_' + x) for x in
        ('multiply', 'multiplied', 'no_carry', 'digit_no_carry', 'finished', 'overflow', 'success'))
    c.mark(multiply)
    c.load('number_count')
    c.jz(multiplied)
    c.load('number_sum')
    c.load('number_acc')
    c.ops(Op.ADD)
    c.store('number_sum')
    c.ops(Op.CARRY)
    c.jz(no_carry)
    set_cell('number_overflow', 1)
    c.mark(no_carry)
    advance('number_count', -1)
    c.jump(multiply)
    c.mark(multiplied)
    c.load('number_sum')
    c.load('number_digit')
    c.ops(Op.ADD)
    c.store('number_acc')
    c.ops(Op.CARRY)
    c.jz(digit_no_carry)
    set_cell('number_overflow', 1)
    c.mark(digit_no_carry)
    advance('number_pos')
    advance('number_left', -1)
    c.load('number_left')
    c.jz(finished)
    c.jump(digits)
    c.mark(finished)
    c.load('number_overflow')
    magnitude = c.label('number_magnitude')
    c.jz(magnitude)
    c.jump(overflow)
    c.mark(magnitude)
    c.load('number_negative')
    c.jz(success)
    c.load('number_acc')
    c.push(32769)
    c.ops(Op.LTU)
    c.jz(overflow)
    c.load('number_acc')
    c.negate()
    c.store('number_acc')
    c.mark(success)
    c.load('number_acc')
    c.store('number_value')
    set_cell('number_status', 1)
    c.jump(end)
    c.mark(overflow)
    set_cell('number_status', 2)
    c.jump(end)
    c.mark(invalid_digit)
    c.ops(Op.DROP)
    c.mark(end)
    c.ops(Op.NOP | 128)

    word('BASE', 0, 1, lambda: c.push('base'))
    def set_base(value):
        set_cell('base', value)
    word('DECIMAL', 0, 0, lambda: set_base(10))
    word('HEX', 0, 0, lambda: set_base(16))
    word('\\', 0, 0, lambda: c.call('skip_line'), flags=1)
    word('(', 0, 0, lambda: c.call('skip_paren'), flags=1)
