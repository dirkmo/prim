\ Standard-image audio driver, 25 MHz. UART-only: load line by line.
\ Integer Hz conversion uses a 16x16 -> 32 bit software product.
HEX
: AUDIO-VOICE ( voice -- ) FFE1 C! ;
: AUDIO-MODE ( mode -- ) FFE2 C! ;
: AUDIO-VOLUME ( volume -- ) FFE3 C! ;
: AUDIO-RATE ( lo hi -- ) FFE6 C! FFE4 ! ;
: AUDIO-DUTY ( duty -- ) FFE7 C! ;
: AUDIO-ATTACK ( ms -- ) FFE8 C! ;
: AUDIO-DECAY ( ms -- ) FFE9 C! ;
: AUDIO-APPLY 1 FFEA C! ;
: AUDIO-TRIGGER 2 FFEA C! ;
: AUDIO-STOP 4 FFEA C! ;
: AUDIO-STOP-ALL 8 FFEA C! ;
: AUDIO-STATUS ( -- flags ) FFEB C@ ;
: AUDIO-ON 1 FFE0 C! ;
: AUDIO-OFF 0 FFE0 C! ;
: AUDIO-MUTE 3 FFE0 C! ;
VARIABLE A-XLO VARIABLE A-XHI VARIABLE A-Y
VARIABLE A-LO VARIABLE A-HI
: A-UM* ( u v -- lo hi )
  A-Y ! A-XLO ! 0 A-XHI ! 0 A-LO ! 0 A-HI !
  BEGIN A-Y @ WHILE
    A-Y @ 1 AND IF
      A-LO @ A-XLO @ + DUP A-LO @ U<
      IF 1 ELSE 0 THEN A-HI @ A-XHI @ + + A-HI ! A-LO !
    THEN
    A-XLO @ F RSHIFT A-XHI @ 2* OR A-XHI !
    A-XLO @ 2* A-XLO ! A-Y @ 1 RSHIFT A-Y !
  REPEAT A-LO @ A-HI @ ;
DECIMAL
: AUDIO-HZ ( hz -- )
  43980 A-UM* DUP 255 AND 8 LSHIFT ROT 8 RSHIFT OR
  SWAP 8 RSHIFT AUDIO-RATE ;
: AUDIO-PULSE 0 AUDIO-MODE ;
: AUDIO-TRIANGLE 1 AUDIO-MODE ;
: AUDIO-SAW 2 AUDIO-MODE ;
: AUDIO-ENVELOPE ( attack-ms decay-ms -- )
  AUDIO-DECAY AUDIO-ATTACK
  65506 C@ 4 OR 65506 C! ;
: AUDIO-CONSTANT 65506 C@ 3 AND 65506 C! ;
: AUDIO-INIT
  AUDIO-STOP-ALL 0 AUDIO-VOICE AUDIO-PULSE
  8 AUDIO-VOLUME 128 AUDIO-DUTY 0 AUDIO-ATTACK 10 AUDIO-DECAY
  AUDIO-ON ;
: TONE ( hz -- )
  0 AUDIO-VOICE AUDIO-PULSE 8 AUDIO-VOLUME 128 AUDIO-DUTY
  AUDIO-HZ AUDIO-TRIGGER ;
: TRI-TONE ( hz -- )
  0 AUDIO-VOICE AUDIO-TRIANGLE 8 AUDIO-VOLUME
  AUDIO-HZ AUDIO-TRIGGER ;
: NOISE ( rate-hz -- )
  3 AUDIO-VOICE AUDIO-PULSE 8 AUDIO-VOLUME
  0 8 AUDIO-ENVELOPE AUDIO-HZ AUDIO-TRIGGER ;
