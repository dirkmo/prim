\ Load audio.fs first. Millisecond delay uses the existing system timer COUNT.
\ Timed demos require 1 ms/count; the optional setup word changes timer mode.
\ Explicitly takes ownership of the system timer; use only when otherwise idle.
: AUDIO-DEMO-TIMER
  0 65524 C! 0 65520 ! -1 65522 ! 3 65524 C! ;
: AUDIO-MS ( ms -- )
  65520 @ BEGIN 2DUP 65520 @ SWAP - SWAP U< WHILE REPEAT 2DROP ;
\ The timer may be configured by another application: these demos require
\ free-running COUNT (AUTO enabled with COMPARE=65535), not a short auto-reload period.
: AUDIO-SCALE
  262 TONE 200 AUDIO-MS 294 TONE 200 AUDIO-MS
  330 TONE 200 AUDIO-MS 349 TONE 200 AUDIO-MS
  392 TONE 200 AUDIO-MS 440 TONE 200 AUDIO-MS
  494 TONE 200 AUDIO-MS 523 TONE 200 AUDIO-MS AUDIO-STOP-ALL ;
: AUDIO-CHORD
  262 TONE
  1 AUDIO-VOICE AUDIO-TRIANGLE 8 AUDIO-VOLUME 330 AUDIO-HZ AUDIO-TRIGGER
  2 AUDIO-VOICE AUDIO-SAW 6 AUDIO-VOLUME 392 AUDIO-HZ AUDIO-TRIGGER ;
: AUDIO-LASER
  0 AUDIO-VOICE AUDIO-PULSE 128 AUDIO-DUTY 12 AUDIO-VOLUME
  0 12 AUDIO-ENVELOPE 2000 AUDIO-HZ AUDIO-TRIGGER
  2000 BEGIN DUP 200 > WHILE 40 - DUP AUDIO-HZ AUDIO-APPLY
  3 AUDIO-MS REPEAT DROP ;
: AUDIO-SIREN
  400 BEGIN DUP 1000 < WHILE DUP TONE 20 + 10 AUDIO-MS REPEAT
  BEGIN DUP 400 > WHILE DUP TONE 20 - 10 AUDIO-MS REPEAT
  DROP AUDIO-STOP-ALL ;
