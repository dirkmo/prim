\ Standalone Prim Forth driver. Load line by line over the existing UART.
\ Definitions must reside below E000. VGA-C! maps only around a VRAM write,
\ so the ordinary Forth dictionary may continue to use SRAM at E000..EFFF.
HEX
VARIABLE VX VARIABLE VY VARIABLE VO
: VGA-CURSOR VX @ FFF8 C! VY @ FFF9 C! ;
: VGA-ADDR VY @ VO @ + 1F AND 50 * E000 + VX @ + ;
: VGA-C! FFF6 C@ 1 OR FFF6 C! C! FFF6 C@ 1E AND FFF6 C! ;
: VGA-CLEAR-ROW
  VY @ VO @ + 1F AND 50 * E000 + DUP 50 +
  BEGIN 2DUP U< WHILE SWAP 20 OVER VGA-C! 1+ SWAP REPEAT 2DROP ;
: VGA-CR
  0 VX ! VY @ 1+ DUP 1E U< IF VY !
  ELSE DROP VO @ 1+ 1F AND VO ! VO @ FFF7 C! VGA-CLEAR-ROW THEN
  VGA-CURSOR ;
: VGA-PUT VGA-ADDR VGA-C! VX @ 1+ DUP 50 =
  IF DROP VGA-CR ELSE VX ! VGA-CURSOR THEN ;
: VGA-BS VX @ IF -1 VX +! 20 VGA-ADDR VGA-C! VGA-CURSOR THEN ;
: VGA-EMIT
  DUP D = IF DROP 0 VX ! VGA-CURSOR ELSE
  DUP A = IF DROP VGA-CR ELSE
  DUP 8 = OVER 7F = OR IF DROP VGA-BS ELSE VGA-PUT THEN THEN THEN ;
: VGA-TYPE
  BEGIN DUP WHILE SWAP DUP C@ VGA-EMIT 1+ SWAP 1- REPEAT 2DROP ;
: VGA-PAGE
  0 VX ! 0 VY ! 0 VO ! 0 FFF7 C!
  E000 BEGIN DUP EA00 U< WHILE 20 OVER VGA-C! 1+ REPEAT DROP VGA-CURSOR ;
: VGA-INIT HERE E000 U< 0= IF ABORT THEN 1E FFF6 C! VGA-PAGE ;
DECIMAL
\ Example: VGA-INIT S" Prim VGA console" VGA-TYPE
\ KEY remains on UART. Existing EMIT/TYPE and interpreter echo stay on UART.
